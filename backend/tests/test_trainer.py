def test_wrong_feature_spec():
    # Training sqrt-built data with raw spec fails recovery check
    truth = [0.15, 1.42, -1.18]
    records = simulate_learners(truth, SQRT_SPEC, n_students=600, n_concepts=4, n_sessions=6, questions_per_session=5, seed=42)
    # Re-extract with raw counts
    from hlr.features import extract_features, ConceptCounts
    raw_records = []
    for r in records:
        raw_x = extract_features(ConceptCounts(r.counts_before["n_right"], r.counts_before["n_wrong"]), RAW_SPEC)
        raw_records.append({
            "p_observed": r.p_observed,
            "delta_days": r.delta_days,
            "x_before": raw_x,
            "n_answers": r.n_answers
        })
    cfg = TrainerConfig(max_iterations=100, learning_rate=0.15, alpha=0.0, lambda_=0.001)
    artifact, _ = train_hlr(raw_records, [0.0, 1.0, -1.0], RAW_SPEC, cfg)
    # The weights under raw spec cannot match the sqrt truth
    matches = all(abs(artifact.theta[j] - truth[j]) < 0.2 for j in range(3))
    assert not matches, "Training sqrt data with raw spec should not recover sqrt truth"

def test_no_side_effects():
    # ModelArtifact and HLR_V0_FIXED must remain completely unmodified
    v0_theta_before = list(HLR_V0_FIXED.theta)
    records = simulate_learners(DEFAULT_LAUNCH_THETA, RAW_SPEC, n_students=10, n_concepts=2, n_sessions=4, seed=42)
    train_hlr(records, [0.5, 0.5, -0.5], RAW_SPEC, TrainerConfig(max_iterations=10))
    assert list(HLR_V0_FIXED.theta) == v0_theta_before

def test_early_stopping():
    train_records = simulate_learners(DEFAULT_LAUNCH_THETA, RAW_SPEC, n_students=20, n_concepts=2, n_sessions=5, seed=42)
    val_records = simulate_learners(DEFAULT_LAUNCH_THETA, RAW_SPEC, n_students=10, n_concepts=2, n_sessions=5, seed=999)
    # Set high max_iterations and small patience
    cfg = TrainerConfig(max_iterations=500, early_stopping_patience=5, learning_rate=0.5)
    artifact, report = train_hlr(train_records, [0.0, 1.0, -1.0], RAW_SPEC, cfg, val_examples=val_records)
    assert report.stopped_iteration < 500

