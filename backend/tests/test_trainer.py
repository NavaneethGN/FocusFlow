from ml.simulator import simulate_learners, DEFAULT_LAUNCH_THETA, DEFAULT_TRAINED_THETA

def test_gradient_check_full_loss():
    # alpha=0.01, lambda=0.1
    cfg = TrainerConfig(alpha=0.01, lambda_=0.1)
    examples = [
        {"p_observed": 0.85, "delta_days": 2.5, "x_before": [1.0, 3.0, 1.0], "n_answers": 5},
        {"p_observed": 0.30, "delta_days": 10.0, "x_before": [1.0, 1.0, 3.0], "n_answers": 4},
        {"p_observed": 0.60, "delta_days": 4.0, "x_before": [1.0, 2.0, 2.0], "n_answers": 5},
    ]
    theta = [0.2, 0.8, -0.6]
    max_rel_err = gradient_check(theta, examples, cfg, eps=1e-6)
    assert max_rel_err < 1e-5, f"Gradient check failed with max_rel_err={max_rel_err}"

def test_gradient_check_special_cases():
    # alpha=0 and lambda=0: reduces to plain squared recall error
    cfg_plain = TrainerConfig(alpha=0.0, lambda_=0.0)
    examples = [
        {"p_observed": 0.90, "delta_days": 1.0, "x_before": [1.0, 2.0, 0.0], "n_answers": 1},
        {"p_observed": 0.40, "delta_days": 5.0, "x_before": [1.0, 0.0, 2.0], "n_answers": 1},
    ]
    theta = [0.1, 0.5, -0.5]
    max_rel_err = gradient_check(theta, examples, cfg_plain, eps=1e-6)
    assert max_rel_err < 1e-5

def test_boundary_labels_finite():
    # p=0 and p=1 produce finite h_target and finite gradients
    cfg = TrainerConfig(alpha=0.01, lambda_=0.1)
    examples = [
        {"p_observed": 0.0, "delta_days": 3.0, "x_before": [1.0, 0.0, 2.0], "n_answers": 5},
        {"p_observed": 1.0, "delta_days": 3.0, "x_before": [1.0, 3.0, 0.0], "n_answers": 5},
    ]
    loss, grad = compute_loss_and_gradient([0.0, 1.0, -1.0], examples, cfg)
    assert math.isfinite(loss)
    for g in grad:
        assert math.isfinite(g)

def test_loss_decreases():
    # Train on small simulated dataset and ensure loss decreases
    records = simulate_learners(DEFAULT_LAUNCH_THETA, RAW_SPEC, n_students=20, n_concepts=3, n_sessions=8, seed=42)
    cfg = TrainerConfig(max_iterations=40, learning_rate=0.1, alpha=0.001, lambda_=0.01)
    artifact, report = train_hlr(records, [0.5, 0.5, -0.5], RAW_SPEC, cfg)
    assert report.losses[-1] < report.losses[0]

def test_recovery_exact_labels():
    # Truth [0, 1, -1] with raw_counts spec, exact labels (~20k records)
    records = simulate_learners(
        DEFAULT_LAUNCH_THETA,
        RAW_SPEC,
        n_students=800,
        n_concepts=5,
        n_sessions=6,
        questions_per_session=2,
        exact_mode=True,
        seed=42
    )
    assert len(records) >= 15000
    cfg = TrainerConfig(max_iterations=150, learning_rate=0.25, alpha=0.005, lambda_=0.0001)
    artifact, report = train_hlr(records, [0.1, 0.8, -0.8], RAW_SPEC, cfg)
    for j in range(3):
        diff = abs(artifact.theta[j] - DEFAULT_LAUNCH_THETA[j])
        assert diff < 0.2, f"Parameter theta[{j}] error {diff} exceeds tolerance"

