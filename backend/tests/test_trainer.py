def test_recovery_and_beats_leitner_baseline():
    # Simulate data generated by [0.15, 1.42, -1.18] with sqrt_counts
    truth = [0.15, 1.42, -1.18]
    train_records = simulate_learners(truth, SQRT_SPEC, n_students=600, n_concepts=4, n_sessions=6, questions_per_session=5, seed=42)
    test_records = simulate_learners(truth, SQRT_SPEC, n_students=200, n_concepts=4, n_sessions=6, questions_per_session=5, seed=999)

    cfg = TrainerConfig(max_iterations=100, learning_rate=0.15, alpha=0.0, lambda_=0.001)
    artifact, report = train_hlr(train_records, [0.0, 1.0, -1.0], SQRT_SPEC, cfg)

    # Weights recovered within tolerance 0.2
    for j in range(3):
        assert abs(artifact.theta[j] - truth[j]) < 0.2

    # Measure MAE on test_records: trained model vs Leitner baseline (hlr_v0_fixed)
    def calc_mae(theta, spec):
        errors = []
        for r in test_records:
            h = predict_half_life(theta, r.x_before)
            p_pred = predict_recall(h, r.delta_days)
            errors.append(abs(r.p_observed - p_pred))
        return float(np.mean(errors))

    trained_mae = calc_mae(artifact.theta, SQRT_SPEC)
    leitner_mae = calc_mae(HLR_V0_FIXED.theta, RAW_SPEC)

    assert trained_mae < leitner_mae, f"Trained MAE {trained_mae} must beat Leitner baseline MAE {leitner_mae}"

def test_l2_shrinkage():
    records = simulate_learners(DEFAULT_LAUNCH_THETA, RAW_SPEC, n_students=20, n_concepts=3, n_sessions=6, seed=42)
    cfg_low = TrainerConfig(lambda_=0.001, max_iterations=40, learning_rate=0.05)
    cfg_high = TrainerConfig(lambda_=5.0, max_iterations=40, learning_rate=0.05)

    art_low, _ = train_hlr(records, [0.5, 1.5, -1.5], RAW_SPEC, cfg_low)
    art_high, _ = train_hlr(records, [0.5, 1.5, -1.5], RAW_SPEC, cfg_high)

    norm_low = math.sqrt(sum(t ** 2 for t in art_low.theta))
    norm_high = math.sqrt(sum(t ** 2 for t in art_high.theta))
    assert norm_high < norm_low

def test_reproducibility():
    records = simulate_learners(DEFAULT_LAUNCH_THETA, RAW_SPEC, n_students=10, n_concepts=2, n_sessions=5, seed=42)
    cfg = TrainerConfig(max_iterations=20)
    art1, rep1 = train_hlr(records, [0.0, 1.0, -1.0], RAW_SPEC, cfg)
    art2, rep2 = train_hlr(records, [0.0, 1.0, -1.0], RAW_SPEC, cfg)
    assert art1.theta == art2.theta
    assert rep1.losses == rep2.losses

